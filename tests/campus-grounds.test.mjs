import test from 'node:test';import assert from 'node:assert/strict';import * as T from 'three';
globalThis.document={createElement:()=>({width:0,height:0,getContext:()=>({fillRect(){},fillText(){},strokeRect(){},beginPath(){},moveTo(){},lineTo(){},arc(){},stroke(){},createRadialGradient:()=>({addColorStop(){}}),fillStyle:'',strokeStyle:'',font:'',textAlign:'',textBaseline:'',lineWidth:0})})};
const {init,clear,groundAt}=await import('../dist/world.js');
init();
const {decorate}=await import('../dist/decor.js');decorate();
const {props}=await import('../dist/props.js');props();
const {architecturalDetails}=await import('../dist/architecture.js');
const {scene,walls}=await import('../dist/world.js');architecturalDetails(scene,walls);
const {roomAt}=await import('../dist/floor-map.js');
const {findPath}=await import('../dist/navigation.js');
test('门厅、厕所、楼梯和操场可走，楼层高度互不重叠',()=>{
 assert.equal(clear(0,-19),true);
 assert.equal(clear(0,-25),true,'门厅应可走');
 assert.equal(clear(0,-21),true,'教学楼南门口内侧应可走');
 assert.equal(clear(0,-22),true,'教学楼南门洞应可走');
 assert.equal(clear(0,-23),true,'门厅入口处应可走');
 assert.equal(roomAt(0,-25),'一层门厅');
 assert.equal(roomAt(-13,-25),'男厕所');
 assert.ok(clear(-13.2,-23.8)||clear(-11.8,-25),'厕所隔间外应可走');
 assert.ok(groundAt(9.4,-24.8)>0.3&&groundAt(9.4,-24.8)<2,'一层楼梯应抬升');
 assert.equal(clear(8.2,-23.0),true,'楼梯入口应可走');
 assert.equal(clear(8.5,-22.8),true,'楼梯门口通道应可走');
 assert.equal(clear(9.4,-22.8),true,'楼梯口中央应可走');
 assert.equal(clear(9.4,-23.2),true,'楼梯第一步应可走');
 const stairs=findPath(new T.Vector3(0,1,-25),new T.Vector3(9.4,1,-26.5));
 assert.ok(stairs.length>0,'门厅应能走上楼梯');
 assert.equal(clear(9.4,-27.6,false,1.76),true,'楼梯平台应可走');
 assert.equal(clear(9.9,-30,false,2.5),true,'二段楼梯应可走');
 const upper=findPath(new T.Vector3(9.4,1,-26.5),new T.Vector3(12,3.52,-35));
 assert.ok(upper.length>0,'楼梯应能上到二楼连廊');
 assert.ok(Math.abs(groundAt(12,-35)-3.52)<.02,'二楼连廊高度');
 assert.equal(roomAt(0,-50),'操场');
 assert.equal(clear(0,-50),true);
 const lobby=findPath(new T.Vector3(0,1,-19),new T.Vector3(0,1,-25));
 assert.ok(lobby.length>0,'出生点应能走到门厅');
 const yard=findPath(new T.Vector3(0,1,-25),new T.Vector3(0,1,-45));
 assert.ok(yard.length>0,'门厅应能走到操场');
});
